# ==========================================
# อัลกอริทึม ขั้นที่ 1: ส่วนหัวข้อและรับข้อมูล
# ==========================================
import streamlit as st  # ระบุคำสั่ง import (ใช้ streamlit สำหรับทำเว็บแอป)

# แสดงชื่อแอปพลิเคชัน
st.title("🏋️ แอปพลิเคชันคำนวณดัชนีมวลกาย (BMI)")

# แสดงข้อความให้ผู้ใช้กรอกข้อมูลน้ำหนักและส่วนสูง
st.write("กรุณากรอกข้อมูลน้ำหนักและส่วนสูงของคุณด้านล่าง:")

# สร้างช่องรับข้อมูลน้ำหนัก (กิโลกรัม)
weight = st.number_input("กรอกน้ำหนัก (กิโลกรัม):", min_value=0.0, step=0.1)

# สร้างช่องรับข้อมูลส่วนสูง (เซนติเมตร)
height_cm = st.number_input("กรอกส่วนสูง (เซนติเมตร):", min_value=0.0, step=0.1)


# ==========================================
# การคำนวณค่า BMI (ขั้นตอนเชื่อมโยง)
# ==========================================
if height_cm > 0:
    height_m = height_cm / 100  # แปลงเซนติเมตรเป็นเมตร
    bmi = weight / (height_m ** 2)
else:
    bmi = 0

# ==========================================
# อัลกอริทึม ขั้นที่ 3: แสดงการแปลผลและข้อมูลผู้จัดทำ
# ==========================================
if st.button("คำนวณผลลัพธ์"):
    st.subheader(f"ค่า BMI ของคุณคือ: {bmi:.2f}")

    # สร้างเงื่อนไข if การแปลผลดัชนีมวลกาย
    if bmi < 18.5:
        st.warning("ผลการแปลผล: ผอม")
    elif 18.5 <= bmi < 23.0:
        st.success("ผลการแปลผล: สุขภาพดี")
    elif 23.0 <= bmi < 25.0:
        st.info("ผลการแปลผล: ท้วม")
    else:
        st.error("ผลการแปลผล: อ้วน")

    # สร้างเส้นกั้น
    st.divider()

    # แสดงชื่อ-สกุล เลขที่ หมายเลขห้องนักเรียน
    st.write("### ข้อมูลผู้จัดทำ")
    st.write("**ชื่อ-นามสกุล:** [ใส่ชื่อ-นามสกุลของคุณ]")
    st.write("**เลขที่:** [ใส่เลขที่]")
    st.write("**ห้องเรียน:** [ใส่หมายเลขห้อง]")
